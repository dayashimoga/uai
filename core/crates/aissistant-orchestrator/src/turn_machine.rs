//! Thread-safe state machine managing turn lifecycle transitions and cancellation flags.

use std::sync::{Arc, Mutex, RwLock};
use std::time::{SystemTime, UNIX_EPOCH};

use aissistant_llm::LlmCancellationHandle;

use crate::error::{OrchestratorError, Result};
use crate::state::TurnState;

/// Metrics collected across the lifetime of a single turn.
#[derive(Debug, Clone, Default)]
pub struct TurnMetrics {
    /// Unix timestamp in milliseconds when the turn was initiated.
    pub start_time_ms: i64,
    /// Time to first token (TTFT) in milliseconds from inference start.
    pub ttft_ms: Option<u64>,
    /// Total elapsed inference latency in milliseconds.
    pub latency_ms: Option<u64>,
    /// Number of tokens generated by the LLM in this turn.
    pub token_count: usize,
    /// Number of memory excerpts retrieved from storage.
    pub memory_hits_count: usize,
    /// Whether the turn was interrupted prematurely.
    pub interrupted: bool,
}

/// Thread-safe turn state machine enforcing valid transitions and managing cooperative cancellation.
#[derive(Debug, Clone)]
pub struct TurnStateMachine {
    current_state: Arc<RwLock<TurnState>>,
    cancellation_handle: Arc<LlmCancellationHandle>,
    metrics: Arc<Mutex<TurnMetrics>>,
}

impl Default for TurnStateMachine {
    fn default() -> Self {
        Self::new()
    }
}

impl TurnStateMachine {
    /// Creates a new `TurnStateMachine` initialized to `TurnState::Idle`.
    #[must_use]
    pub fn new() -> Self {
        Self {
            current_state: Arc::new(RwLock::new(TurnState::Idle)),
            cancellation_handle: Arc::new(LlmCancellationHandle::new()),
            metrics: Arc::new(Mutex::new(TurnMetrics::default())),
        }
    }

    /// Returns the current state of the turn machine.
    #[must_use]
    pub fn state(&self) -> TurnState {
        self.current_state
            .read()
            .map(|guard| *guard)
            .unwrap_or(TurnState::Failed)
    }

    /// Evaluates and applies a state transition, returning an error if illegal.
    pub fn transition_to(&self, target: TurnState) -> Result<TurnState> {
        let mut guard = self.current_state.write().map_err(|e| {
            OrchestratorError::Internal(format!("Failed to acquire state write lock: {e}"))
        })?;

        let current = *guard;
        if !current.can_transition_to(target) {
            return Err(OrchestratorError::InvalidStateTransition {
                from: current.to_string(),
                to: target.to_string(),
                reason: format!(
                    "Transition from {current} to {target} is disallowed by the turn protocol"
                ),
            });
        }

        *guard = target;
        Ok(target)
    }

    /// Resets state and cancellation flag for a new turn.
    pub fn reset_for_new_turn(&self) -> Result<()> {
        let mut guard = self.current_state.write().map_err(|e| {
            OrchestratorError::Internal(format!("Failed to acquire state write lock: {e}"))
        })?;

        *guard = TurnState::Idle;
        self.cancellation_handle.reset();

        if let Ok(mut m) = self.metrics.lock() {
            *m = TurnMetrics {
                start_time_ms: current_time_ms(),
                ..Default::default()
            };
        }

        Ok(())
    }

    /// Returns the thread-safe cooperative cancellation handle for the current turn.
    #[must_use]
    pub fn cancellation_handle(&self) -> Arc<LlmCancellationHandle> {
        Arc::clone(&self.cancellation_handle)
    }

    /// Triggers immediate cooperative cancellation and records interruption.
    pub fn trigger_cancellation(&self) {
        self.cancellation_handle.cancel();
        if let Ok(mut m) = self.metrics.lock() {
            m.interrupted = true;
        }
        let _ = self.transition_to(TurnState::Interrupted);
    }

    /// Records time to first token (TTFT).
    pub fn record_ttft(&self, ttft_ms: u64) {
        if let Ok(mut m) = self.metrics.lock() {
            if m.ttft_ms.is_none() {
                m.ttft_ms = Some(ttft_ms);
            }
        }
    }

    /// Increments generated token count.
    pub fn record_token(&self) {
        if let Ok(mut m) = self.metrics.lock() {
            m.token_count += 1;
        }
    }

    /// Records memory retrieval hit count.
    pub fn record_memory_hits(&self, count: usize) {
        if let Ok(mut m) = self.metrics.lock() {
            m.memory_hits_count = count;
        }
    }

    /// Closes turn metrics and computes total latency.
    pub fn finalize_metrics(&self) -> TurnMetrics {
        let mut m = self.metrics.lock().map(|g| g.clone()).unwrap_or_default();
        let now = current_time_ms();
        if m.start_time_ms > 0 && now >= m.start_time_ms {
            m.latency_ms = Some((now - m.start_time_ms) as u64);
        }
        m
    }
}

fn current_time_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn test_turn_state_machine_happy_path() {
        let sm = TurnStateMachine::new();
        assert_eq!(sm.state(), TurnState::Idle);

        sm.transition_to(TurnState::UtteranceReceived).unwrap();
        assert_eq!(sm.state(), TurnState::UtteranceReceived);

        sm.transition_to(TurnState::RetrievingMemory).unwrap();
        assert_eq!(sm.state(), TurnState::RetrievingMemory);

        sm.transition_to(TurnState::PromptAssembly).unwrap();
        sm.transition_to(TurnState::Inferring).unwrap();
        sm.transition_to(TurnState::TurnCompleted).unwrap();
        sm.transition_to(TurnState::Idle).unwrap();
        assert_eq!(sm.state(), TurnState::Idle);
    }

    #[test]
    fn test_turn_state_machine_invalid_transition() {
        let sm = TurnStateMachine::new();
        let err = sm.transition_to(TurnState::SynthesizingSpeech).unwrap_err();
        assert!(matches!(
            err,
            OrchestratorError::InvalidStateTransition { ref from, ref to, .. }
                if from == "idle" && to == "synthesizing_speech"
        ));
    }

    #[test]
    fn test_cooperative_cancellation_barge_in() {
        let sm = TurnStateMachine::new();
        sm.transition_to(TurnState::UtteranceReceived).unwrap();
        sm.transition_to(TurnState::Inferring).unwrap();

        assert!(!sm.cancellation_handle().is_cancelled());
        sm.trigger_cancellation();
        assert!(sm.cancellation_handle().is_cancelled());
        assert_eq!(sm.state(), TurnState::Interrupted);

        let metrics = sm.finalize_metrics();
        assert!(metrics.interrupted);
    }
}
